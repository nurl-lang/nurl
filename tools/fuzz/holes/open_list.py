#!/usr/bin/env python3
"""The soundness holes known open, one file each: tools/fuzz/holes/open/t<N>.md.

Every PR that closed a hole used to edit the same sentence and list in
docs/LIMITATIONS.md ("Six soundness holes are known open…") and the same
list in docs/MEMORY.md §6.2, so any two hole PRs conflicted there and the
second rebased and ran CI again (Agora #136; the changelog had the same
problem, #211). Now a hole is a file:

  * a PR that finds a hole it does not fix adds tools/fuzz/holes/open/t<N>.md
    (N = its Agora task): one paragraph, `**agora #N: <shape>.** <what
    happens>. Until the fix ships, <how to stay clear of it>.`;
  * the PR that closes it deletes that file.

No two PRs touch the same file. The list in docs/LIMITATIONS.md (between
the BEGIN/END markers) is generated from the files at release time, like
the changelog fold (RELEASING.md step 2), and release.yml's verify-ci
checks it on the tag.

  open_list.py --write   regenerate the list in docs/LIMITATIONS.md
  open_list.py --check   fail when the list is not what the files say
  open_list.py --known-issues [CLOSED]
                         print the release's Known issues entry from the
                         same files (CLOSED: "agora #224, #229 …", the holes
                         the release closed), ready for CHANGELOG.md
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
OPEN = ROOT / "tools/fuzz/holes/open"
DOC = ROOT / "docs/LIMITATIONS.md"
BEGIN = "<!-- BEGIN open holes: generated by tools/fuzz/holes/open_list.py from tools/fuzz/holes/open/t*.md -->"
END = "<!-- END open holes -->"
WORDS = ["No", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight",
         "Nine", "Ten", "Eleven", "Twelve", "Thirteen", "Fourteen", "Fifteen",
         "Sixteen", "Seventeen", "Eighteen", "Nineteen", "Twenty"]


def holes():
    files = sorted(OPEN.glob("t*.md"), key=lambda p: int(re.sub(r"\D", "", p.stem) or 0))
    out = []
    for f in files:
        text = f.read_text().strip()
        n = re.sub(r"\D", "", f.stem)
        if not text.startswith(f"**agora #{n}:"):
            sys.exit(f"open_list.py: {f.relative_to(ROOT)} must start with `**agora #{n}: …**`")
        out.append(text)
    return out


def render(items):
    n = len(items)
    count = WORDS[n] if n < len(WORDS) else str(n)
    if n == 0:
        head = ("**No soundness hole is known open** "
                "([`MEMORY.md` §6.2](MEMORY.md)).")
        return f"{BEGIN}\n{head}\n{END}"
    verb = "hole is" if n == 1 else "holes are"
    head = (f"**{count} soundness {verb} known open** ([`MEMORY.md` §6.2](MEMORY.md)).\n"
            "Each is a use of freed or moved-out memory in safe code, with a fix in progress:")
    bullets = []
    for text in items:
        lines = text.split("\n")
        bullets.append("- " + lines[0] + "".join("\n  " + l if l else "\n" for l in lines[1:]))
    return f"{BEGIN}\n{head}\n\n" + "\n".join(bullets) + f"\n{END}"


def known_issues(closed):
    """The CHANGELOG Known issues bullet: every open hole by its shape."""
    import textwrap
    items = []
    for text in holes():
        flat = " ".join(text.split())
        m = re.match(r"\*\*agora #(\d+): (.+?)\.?\*\*", flat)
        shape = m.group(2)
        items.append((m.group(1), shape[0].lower() + shape[1:]))
    n = len(items)
    if n == 0:
        head = "- **No soundness hole is known open.**"
        body = ""
    else:
        count = WORDS[n] if n < len(WORDS) else str(n)
        verb = "hole is" if n == 1 else "holes are"
        parts = [f"#{k} ({s})" for k, s in items]
        parts[0] = "agora " + parts[0]
        lst = parts[0] if n == 1 else ", ".join(parts[:-1]) + " and " + parts[-1]
        head = f"- **{count} soundness {verb} open, each with a fix in progress**:"
        body = (f" {lst}. `docs/LIMITATIONS.md` gives each one's shape and how to"
                " stay clear of it.")
    tail = f" Closed in this release: {closed}." if closed else ""
    tail += ' A release does not say "no hole is known open" while one is.' if n else ""
    return textwrap.fill(head + body + tail, 72, subsequent_indent="  ",
                         break_long_words=False, break_on_hyphens=False)


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else "--check"
    if mode == "--known-issues":
        print(known_issues(sys.argv[2] if len(sys.argv) > 2 else ""))
        return
    doc = DOC.read_text()
    if BEGIN not in doc or END not in doc:
        sys.exit("open_list.py: docs/LIMITATIONS.md has no BEGIN/END open holes markers")
    a = doc.index(BEGIN)
    b = doc.index(END) + len(END)
    want = render(holes())
    if mode == "--write":
        DOC.write_text(doc[:a] + want + doc[b:])
        print(f"open_list.py: {len(holes())} open hole(s) written to docs/LIMITATIONS.md")
    elif mode == "--check":
        if doc[a:b] != want:
            sys.exit("open_list.py: docs/LIMITATIONS.md's open-hole list is stale; "
                     "run tools/fuzz/holes/open_list.py --write")
        print(f"open_list.py: docs/LIMITATIONS.md lists the {len(holes())} open hole(s)")
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
