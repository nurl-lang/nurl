// Generate webdocs' static benchmark table from the latest measurement run:
// bench/results/latest.json, which bench.yml publishes to the bench-data
// branch and webdocs' prebuild fetches (tools/bench_data.sh, Agora #290).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const RESULTS = join(ROOT, 'bench', 'results', 'latest.json');
const OUTPUT = join(ROOT, 'webdocs', 'lib', 'benchmark-stats.generated.ts');
// NURL is always first: the homepage highlights column 0.
const LANGUAGES = [
  ['nurl', 'NURL'],
  ['c', 'C'],
  ['rust', 'Rust'],
  ['node', 'Node'],
  ['python', 'Python'],
];

function formatMs(value) {
  if (value === null || value === undefined || Number.isNaN(value)) return 'n/a';
  return value < 10 ? `${value.toFixed(1)} ms` : `${Math.round(value).toLocaleString('en-US')} ms`;
}

let results;
try {
  results = JSON.parse(readFileSync(RESULTS, 'utf8'));
} catch (err) {
  console.error(`gen-bench-table: cannot read ${RESULTS}: ${err.message}`);
  console.error('gen-bench-table: the numbers live on the bench-data branch: tools/bench_data.sh fetch bench/results/latest.json');
  process.exit(1);
}

const rows = (results.benchmarks ?? []).filter((bench) => bench.verified !== false);
if (rows.length === 0) {
  console.error('gen-bench-table: no verified benchmarks in the results file');
  process.exit(1);
}

const generatedRows = rows.map((bench) => {
  const raw = LANGUAGES.map(([key]) => bench.run_ms?.[key] ?? null);
  const values = raw.map(formatMs);
  const finite = raw.filter((value) => typeof value === 'number' && Number.isFinite(value));
  const best = finite.length ? formatMs(Math.min(...finite)) : null;
  return {
    name: bench.name,
    blurb: bench.blurb ?? '',
    values,
    nurlWins: best !== null && values[0] === best && !values.slice(1).includes(best),
  };
});

const stats = {
  benchmarks: generatedRows.length,
  languages: LANGUAGES.length,
  generated: (results.generated_utc ?? '').slice(0, 10),
  runUrl: results.run_url ?? '',
  host: results.host?.label ?? 'unknown host',
  columns: LANGUAGES.map(([, label]) => label),
  rows: generatedRows,
};

writeFileSync(OUTPUT, `// Generated by tools/gen-bench-table.mjs.\nexport const benchmarkStats = ${JSON.stringify(stats, null, 2)} as const;\n`);
console.log(`benchmark stats → ${OUTPUT}\n  ${stats.benchmarks} benchmarks × ${stats.languages} languages, measured ${stats.generated}`);
