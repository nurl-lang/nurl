#!/usr/bin/env python3
"""formal/RULES.md's change table, one file per change: formal/rules/t<N>.md.

Every ownership change added a row at the end of the table "Changes to
MEMORY.md and what they do to the proof" in formal/RULES.md, so any two
such PRs conflicted there, and the second rebased and ran CI again
(Agora #299; the changelog, #211, and the open-hole list, #136, had the
same problem). Now a change's row is a file:

  * a PR that changes an ownership rule adds formal/rules/t<N>.md
    (N = its Agora task; t<N>-<slug>.md for another file of the same
    task), holding its row(s) exactly as the table shows them, one line
    each: `| Change | MEMORY.md | Touches a proven rule? | Effect |`;
  * a PR that revises a row edits that row's file. t0.md holds the rows
    of changes that had no task (the history from before the board).

No two PRs edit the same file. The table in formal/RULES.md, between the
BEGIN/END markers, is written from the files at release time, in task
order (RELEASING.md step 2, beside open_list.py), and release.yml's
verify-ci checks it on the tag. CI's shared-files job lints the files on
every PR; the table itself lags main until the release regenerates it.

  formal_rules.py --write   regenerate the table in formal/RULES.md
  formal_rules.py --check   fail when the table is not what the files say
  formal_rules.py --lint    fail when a row file is malformed (every PR)
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
ROWS = ROOT / "formal/rules"
DOC = ROOT / "formal/RULES.md"
BEGIN = "<!-- BEGIN change rows: generated by tools/formal_rules.py from formal/rules/t*.md -->"
END = "<!-- END change rows -->"
HEADER = "| Change | MEMORY.md | Touches a proven rule? | Effect |\n|---|---|---|---|"
NAME = re.compile(r"t(\d+)(-[a-z0-9][a-z0-9-]*)?\.md")
# A cell may hold an escaped pipe (`\|`); only the others separate cells.
PIPE = re.compile(r"(?<!\\)\|")


def die(msg):
    sys.exit(f"formal_rules.py: {msg}")


def rel(p):
    return p.relative_to(ROOT)


def row_files():
    """The row files in table order: by task number; t<N>.md before its
    t<N>-<slug>.md files, which go by slug."""
    out = []
    for f in ROWS.glob("*"):
        if f.name == "README.md":
            continue
        m = NAME.fullmatch(f.name)
        if not m:
            die(f"{rel(f)}: a row file is named t<N>.md or t<N>-<slug>.md (N: its Agora task)")
        out.append((int(m.group(1)), m.group(2) or "", f))
    out.sort(key=lambda t: t[:2])
    return [f for _, _, f in out]


def rows_of(f):
    rows = []
    for i, line in enumerate(f.read_text().split("\n"), 1):
        if not line.strip():
            continue
        if not (line.startswith("| ") and line.endswith(" |")) or len(PIPE.split(line)) != 6:
            die(f"{rel(f)}:{i}: not one table row of four cells, "
                "`| Change | MEMORY.md | Touches a proven rule? | Effect |`")
        rows.append(line)
    if not rows:
        die(f"{rel(f)}: holds no row")
    return rows


def all_rows():
    rows, seen = [], {}
    for f in row_files():
        for r in rows_of(f):
            if r in seen:
                die(f"{rel(f)}: the same row as {rel(seen[r])}")
            seen[r] = f
            rows.append(r)
    return rows


def render(rows):
    return f"{BEGIN}\n{HEADER}\n" + "".join(r + "\n" for r in rows) + END


def table_rows(region):
    return [l for l in region.split("\n")[3:-1] if l]


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else "--check"
    if mode not in ("--write", "--check", "--lint"):
        sys.exit(__doc__)
    doc = DOC.read_text()
    if doc.count(BEGIN) != 1 or doc.count(END) != 1 or doc.index(BEGIN) > doc.index(END):
        die("formal/RULES.md needs one BEGIN and one END change-rows marker, in that order")
    a = doc.index(BEGIN)
    b = doc.index(END) + len(END)
    rows = all_rows()
    want = render(rows)
    if mode == "--write":
        # A row the table has and no file holds is either one a file has
        # since revised, or one written into the table by hand, which the
        # regeneration drops: name them, so the release can tell which.
        gone = [r for r in table_rows(doc[a:b]) if r not in set(rows)]
        for r in gone:
            print(f"formal_rules.py: not in any file, dropped: {r[:100]}…", file=sys.stderr)
        DOC.write_text(doc[:a] + want + doc[b:])
        print(f"formal_rules.py: {len(rows)} row(s) from {len(row_files())} file(s) "
              "written to formal/RULES.md")
    elif mode == "--check":
        if doc[a:b] != want:
            die("formal/RULES.md's change table is not what formal/rules/ says; "
                "run tools/formal_rules.py --write")
    else:
        print(f"formal_rules.py: {len(row_files())} row file(s), {len(rows)} row(s) OK")


if __name__ == "__main__":
    main()
